import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { platformServices } from "../config/platform-services.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedJsonPath = resolve(root, "config/platform-services.generated.json");
const generatedTypescriptPath = resolve(root, "services/gateway/src/generated/platform-service-manifest.ts");

function fail(message) {
  throw new Error(`Invalid platform service manifest: ${message}`);
}

export function validateServiceManifest(manifest) {
  if (manifest?.apiVersion !== 1) fail("apiVersion must be 1");
  for (const environment of ["production", "staging"]) {
    try { new URL(manifest.origins[environment]); } catch { fail(`${environment} origin must be an absolute URL`); }
  }
  const ids = new Set();
  const names = { production: new Set(), staging: new Set() };
  for (const [index, service] of manifest.services.entries()) {
    if (!/^[a-z][a-z0-9-]*$/.test(service.id)) fail(`invalid service id ${service.id}`);
    if (ids.has(service.id)) fail(`duplicate service id ${service.id}`);
    ids.add(service.id);
    if (service.deployOrder !== index) fail(`deployOrder for ${service.id} must be ${index}`);
    if (!service.config?.startsWith("services/")) fail(`${service.id} config must live under services/`);
    for (const environment of ["production", "staging"]) {
      const key = `${environment}Name`;
      if (!service[key]) fail(`${service.id} is missing ${key}`);
      if (names[environment].has(service[key])) fail(`duplicate ${environment} worker ${service[key]}`);
      names[environment].add(service[key]);
    }
  }
  if (manifest.services.at(-1)?.id !== "gateway" || !manifest.services.at(-1)?.promoteVersion) {
    fail("gateway must be the final version-promoted service");
  }
  for (const [groupName, group] of Object.entries(manifest.gateway.routeGroups)) {
    for (const path of [...(group.exact ?? []), ...(group.prefixes ?? []), ...(group.excludeExact ?? [])]) {
      if (!path.startsWith("/")) fail(`${groupName} route must start with /: ${path}`);
    }
    for (const pattern of group.patterns ?? []) {
      try { new RegExp(pattern); } catch { fail(`${groupName} contains invalid pattern ${pattern}`); }
    }
  }
  const allNames = new Set([...names.production, ...names.staging]);
  for (const [owner, environments] of Object.entries(manifest.bindings)) {
    for (const [environment, bindings] of Object.entries(environments)) {
      for (const [binding, target] of Object.entries(bindings)) {
        if (!allNames.has(target)) fail(`${owner}.${environment}.${binding} targets unknown worker ${target}`);
      }
    }
  }
  return manifest;
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function generatedTypescript(manifest) {
  const payload = {
    origins: manifest.origins,
    runWorkerFirst: manifest.gateway.runWorkerFirst,
    routeGroups: manifest.gateway.routeGroups,
  };
  return `// Generated by scripts/generated-service-manifest.mjs. Do not edit.\n`
    + `export const PLATFORM_GATEWAY_MANIFEST = ${JSON.stringify(payload, null, 2)} as const;\n\n`
    + `export type GatewayRouteGroup = keyof typeof PLATFORM_GATEWAY_MANIFEST.routeGroups;\n\n`
    + `export function matchesGatewayRoute(groupName: GatewayRouteGroup, pathname: string): boolean {\n`
    + `  const group = PLATFORM_GATEWAY_MANIFEST.routeGroups[groupName] as { readonly exact?: readonly string[]; readonly prefixes?: readonly string[]; readonly patterns?: readonly string[]; readonly excludeExact?: readonly string[] };\n`
    + `  if (group.excludeExact?.includes(pathname)) return false;\n`
    + `  return Boolean(group.exact?.includes(pathname)\n`
    + `    || group.prefixes?.some((prefix) => pathname.startsWith(prefix))\n`
    + `    || group.patterns?.some((pattern) => new RegExp(pattern).test(pathname)));\n`
    + `}\n`;
}

function bindingMap(config, environment) {
  const services = environment === "production" ? config.services : config.env?.staging?.services;
  return Object.fromEntries((services ?? []).map(({ binding, service }) => [binding, service]));
}

function assertEqual(actual, expected, label) {
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    fail(`${label} drifted from config/platform-services.mjs`);
  }
}

function configuredWorkerNames(path, source) {
  if (path.endsWith(".jsonc")) {
    const config = JSON.parse(source);
    return {
      production: config.name,
      staging: config.env?.staging?.name ?? `${config.name}-staging`,
    };
  }
  const production = source.match(/^name\s*=\s*"([^"]+)"/m)?.[1];
  const stagingSection = source.split(/^\[env\.staging\]\s*$/m)[1] ?? "";
  const staging = stagingSection.match(/^name\s*=\s*"([^"]+)"/m)?.[1];
  return { production, staging };
}

function validateWranglerConfiguration(manifest) {
  const gateway = JSON.parse(readFileSync(resolve(root, "services/gateway/wrangler.jsonc"), "utf8"));
  const coreApi = JSON.parse(readFileSync(resolve(root, "services/core-api/wrangler.jsonc"), "utf8"));
  assertEqual(gateway.name, manifest.services.find(({ id }) => id === "gateway").productionName, "gateway production name");
  assertEqual(gateway.env.staging.name, manifest.services.find(({ id }) => id === "gateway").stagingName, "gateway staging name");
  assertEqual(gateway.routes, manifest.gateway.productionRoutes, "gateway production routes");
  assertEqual(gateway.env.staging.routes, [], "gateway staging routes");
  assertEqual(gateway.assets.run_worker_first, manifest.gateway.runWorkerFirst, "gateway worker-first routes");
  assertEqual(gateway.vars.PUBLIC_APP_ORIGIN, manifest.origins.production, "gateway production origin");
  assertEqual(gateway.env.staging.vars.PUBLIC_APP_ORIGIN, manifest.origins.staging, "gateway staging origin");
  assertEqual(bindingMap(gateway, "production"), manifest.bindings.gateway.production, "gateway production bindings");
  assertEqual(bindingMap(gateway, "staging"), manifest.bindings.gateway.staging, "gateway staging bindings");
  assertEqual(coreApi.name, manifest.services.find(({ id }) => id === "core-api").productionName, "core API production name");
  assertEqual(bindingMap(coreApi, "production"), manifest.bindings.coreApi.production, "core API production bindings");
  assertEqual(bindingMap(coreApi, "staging"), manifest.bindings.coreApi.staging, "core API staging bindings");

  for (const service of manifest.services) {
    const source = readFileSync(resolve(root, service.config), "utf8");
    const names = configuredWorkerNames(service.config, source);
    assertEqual(names.production, service.productionName, `${service.id} production worker name`);
    assertEqual(names.staging, service.stagingName, `${service.id} staging worker name`);
  }
}

export function renderGeneratedServiceManifest(manifest = platformServices) {
  validateServiceManifest(manifest);
  return {
    json: stableJson(manifest),
    typescript: generatedTypescript(manifest),
  };
}

export function main(args = process.argv.slice(2)) {
  const check = args.length === 1 && args[0] === "--check";
  if ((!check && args.length !== 0) || (check && args.length !== 1)) {
    throw new Error("Usage: node scripts/generated-service-manifest.mjs [--check]");
  }
  validateWranglerConfiguration(validateServiceManifest(platformServices));
  const generated = renderGeneratedServiceManifest();
  const outputs = [
    [generatedJsonPath, generated.json],
    [generatedTypescriptPath, generated.typescript],
  ];
  if (check) {
    for (const [path, expected] of outputs) {
      let actual = "";
      try { actual = readFileSync(path, "utf8"); } catch { /* reported as drift below */ }
      if (actual !== expected) throw new Error(`${path.slice(root.length + 1)} is stale; run npm run routes:generate`);
    }
    process.stdout.write("Generated gateway routes and service configuration are current.\n");
    return;
  }
  for (const [path, contents] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
  process.stdout.write("Generated gateway routes and service configuration.\n");
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
