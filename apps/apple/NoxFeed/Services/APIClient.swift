import Foundation

enum APIError: Error, LocalizedError {
    case unauthorized
    case network(URLError)
    case status(Int, String?)
    case capabilityUnavailable
    case decoding(Error)

    var errorDescription: String? {
        switch self {
        case .unauthorized: return "Session expired. Please sign in again."
        case .network(let e): return e.localizedDescription
        case .status(let code, let body):
            if code >= 500 {
                return "NoxConnect couldn't load this view (HTTP \(code)). Select Retry. If it keeps happening, check NoxConnect service status."
            }
            if let message = Self.safeResponseMessage(from: body) {
                return "Request failed (HTTP \(code)): \(message)"
            }
            return "Request failed (HTTP \(code)). Check your connection and try again."
        case .capabilityUnavailable:
            return "NoxConnect management is not available on the connected server yet."
        case .decoding(let error):
            return "NoxConnect returned an incompatible response (\(Self.decodingDetail(error)))."
        }
    }

    private static func decodingDetail(_ error: Error) -> String {
        func path(_ codingPath: [CodingKey], appending key: CodingKey? = nil) -> String {
            let parts = codingPath.map(\.stringValue) + (key.map { [$0.stringValue] } ?? [])
            return parts.isEmpty ? "the response" : parts.joined(separator: ".")
        }
        switch error {
        case DecodingError.keyNotFound(let key, let context):
            return "missing \(path(context.codingPath, appending: key))"
        case DecodingError.valueNotFound(_, let context):
            return "missing value at \(path(context.codingPath))"
        case DecodingError.typeMismatch(_, let context):
            return "unexpected value at \(path(context.codingPath))"
        case DecodingError.dataCorrupted(let context):
            return "invalid data at \(path(context.codingPath))"
        default:
            return "invalid data"
        }
    }

    /// API errors may be generated by our JSON handlers or by an upstream
    /// proxy such as Cloudflare. Never put an HTML error document into the
    /// native UI; retain only a short JSON/plain-text explanation that gives
    /// the user something actionable.
    private static func safeResponseMessage(from body: String?) -> String? {
        guard let body else { return nil }
        let trimmed = body.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.hasPrefix("<") else { return nil }

        if let data = trimmed.data(using: .utf8),
           let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] {
            for key in ["error", "message"] {
                if let value = json[key] as? String, !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    return String(value.trimmingCharacters(in: .whitespacesAndNewlines).prefix(240))
                }
            }
            if let error = json["error"] as? [String: Any],
               let value = error["message"] as? String,
               !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                return String(value.trimmingCharacters(in: .whitespacesAndNewlines).prefix(240))
            }
            return nil
        }

        return String(trimmed.prefix(240))
    }
}

extension Error {
    var userFacingDescription: String {
        (self as? LocalizedError)?.errorDescription ?? localizedDescription
    }
}

