    func excludedMembers(from settings: [String: AnyJSON]) -> Set<String> {
        guard case let .array(arr)? = settings["excludedMembers"] else { return [] }
        var out = Set<String>()
        for v in arr {
            if case let .string(s) = v { out.insert(s) }
        }
        return out
    }

    func settingsWithExcludedMembers(_ base: [String: AnyJSON], _ members: Set<String>) -> [String: AnyJSON] {
        var out = base
        out["excludedMembers"] = .array(members.sorted().map { .string($0) })
        return out
    }

