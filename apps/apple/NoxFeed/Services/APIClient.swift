    // MARK: - HTTP core

    private func endpoint(_ path: String, queryItems: [URLQueryItem] = []) -> URL {
        guard !queryItems.isEmpty else { return baseURL.appendingPathComponent(path) }
        var components = URLComponents(url: baseURL.appendingPathComponent(path), resolvingAgainstBaseURL: false)!
        components.queryItems = queryItems
        return components.url!
    }

    private func getDecoded<Value: Decodable>(_ type: Value.Type, from url: URL) async throws -> Value {
        try decode(type, from: await get(url))
    }

    /// A missing Pages Function falls through to the website shell with HTTP
    /// 200. Treat that as an unavailable server capability, not malformed
    /// user data or a Swift decoding failure.
    private func getServiceConfig<Value: Decodable>(_ type: Value.Type, from url: URL) async throws -> Value {
        let data = try await get(url)
        guard (try? JSONSerialization.jsonObject(with: data)) != nil else {
            throw APIError.capabilityUnavailable
        }
        return try decode(type, from: data)
    }

    /// Fetch a complete paginated collection. The safety ceiling prevents an
    /// API that ignores `page` from creating an unbounded request loop.
    private func fetchAllPages<Value: Decodable>(
        _ type: Value.Type,
        path: String,
        queryItems: [URLQueryItem],
        pageSize: Int,
        maxPages: Int = 50
    ) async throws -> [Value] {
        let size = min(max(pageSize, 1), 100)
        var values: [Value] = []
        for pageNumber in 1...maxPages {
            let page = try await getDecoded(
                PagedResponse<Value>.self,
                from: endpoint(path, queryItems: queryItems + [
                    URLQueryItem(name: "page_size", value: String(size)),
                    URLQueryItem(name: "page", value: String(pageNumber)),
                ])
            )
            values.append(contentsOf: page.data)
            if page.data.count < size { break }
            if let totalCount = page.totalCount, values.count >= totalCount { break }
        }
        return values
    }

    private func decode<Value: Decodable>(_ type: Value.Type, from data: Data) throws -> Value {
        do { return try decoder.decode(type, from: data) }
        catch {
            let apiError = APIError.decoding(error)
            NSLog("NoxHere API response decoding failed: %@", apiError.errorDescription ?? "invalid data")
            throw apiError
        }
    }

    private func get(_ url: URL) async throws -> Data {
        var req = URLRequest(url: url)
        req.httpMethod = "GET"
        try await attachBearer(&req)
        attachOrg(&req)
        return try await sendWithRefresh(req)
    }

    private func attachBearer(_ req: inout URLRequest) async throws {
        if tokenProvider() == nil {
            guard await refreshHandler() else { throw APIError.unauthorized }
        }
        guard let token = tokenProvider() else { throw APIError.unauthorized }
        req.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
    }

    private func attachOrg(_ req: inout URLRequest) {
        req.setValue(org ?? "", forHTTPHeaderField: "X-Org")
    }

    private func sendWithRefresh(_ original: URLRequest) async throws -> Data {
        let (data, resp) = try await send(original)
        guard let http = resp as? HTTPURLResponse else { return data }
        if http.statusCode != 401 { return try okOrThrow(http, data) }
        guard await refreshHandler() else { throw APIError.unauthorized }
        var replay = original
        try await attachBearer(&replay)
        let (data2, resp2) = try await send(replay)
        guard let http2 = resp2 as? HTTPURLResponse else { return data2 }
        return try okOrThrow(http2, data2)
    }

    private func send(_ req: URLRequest) async throws -> (Data, URLResponse) {
        do { return try await session.data(for: req) }
        catch let e as URLError { throw APIError.network(e) }
    }

    private func okOrThrow(_ http: HTTPURLResponse, _ data: Data) throws -> Data {
        if (200..<300).contains(http.statusCode) { return data }
        let body = String(data: data, encoding: .utf8)
        throw APIError.status(http.statusCode, body)
    }
}

/// Minimal Codable JSON representation — lets us round-trip the `settings`
/// blob without modeling every key we don't touch (so a Mac PUT preserves
/// fields added later by the web).
enum AnyJSON: Codable, Hashable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([AnyJSON])
    case object([String: AnyJSON])

    init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() { self = .null; return }
        if let b = try? c.decode(Bool.self) { self = .bool(b); return }
        if let n = try? c.decode(Double.self) { self = .number(n); return }
        if let s = try? c.decode(String.self) { self = .string(s); return }
        if let a = try? c.decode([AnyJSON].self) { self = .array(a); return }
        if let o = try? c.decode([String: AnyJSON].self) { self = .object(o); return }
        throw DecodingError.dataCorruptedError(in: c, debugDescription: "Unsupported JSON value")
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .null: try c.encodeNil()
        case .bool(let b): try c.encode(b)
        case .number(let n): try c.encode(n)
        case .string(let s): try c.encode(s)
        case .array(let a): try c.encode(a)
        case .object(let o): try c.encode(o)
        }
    }
}
