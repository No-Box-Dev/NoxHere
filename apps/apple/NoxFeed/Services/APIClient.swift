    /// Latest events of every type, newest first — no type/trigger filter.
    /// The notifier polls this and dispatches on `event.type` client-side,
    /// so one request covers opened/merged/review events per tick.
    func fetchRecentEvents(limit: Int = 50, before: String? = nil) async throws -> FeedPage {
        var items = [URLQueryItem(name: "limit", value: String(limit))]
        if let before { items.append(URLQueryItem(name: "before", value: before)) }
        return try await getDecoded(FeedPage.self, from: endpoint("/api/v1/events", queryItems: items))
    }

    /// Page backward until the stored notifier watermark is reached. This
    /// prevents a busy org from losing events when more than one page arrives
    /// between polling ticks.
    func fetchRecentEvents(
        after watermark: Int64,
        startingWith firstPage: FeedPage? = nil
    ) async throws -> [FeedEvent] {
        var events = firstPage?.events ?? []
        if events.contains(where: { $0.id <= watermark }) {
            return events.filter { $0.id > watermark }
        }
        var cursor = firstPage?.nextCursor
        if firstPage != nil && cursor == nil {
            return events.filter { $0.id > watermark }
        }
        while true {
            let page = try await fetchRecentEvents(limit: 200, before: cursor)
            events.append(contentsOf: page.events)
            if page.events.contains(where: { $0.id <= watermark }) { break }
            guard let next = page.nextCursor,
                  next != cursor,
                  !page.events.isEmpty else { break }
            cursor = next
        }
        return events.filter { $0.id > watermark }
    }

    /// Pages backward until the requested time window is covered. Status
    /// activity is org-wide, so a busy org can easily have more than one
    /// page in three days; stopping at a fixed 200 rows would silently show
    /// an older fallback status on quieter PRs.
    func fetchRecentEvents(since: Date, maxPages: Int = 20) async throws -> [FeedEvent] {
        var events: [FeedEvent] = []
        var cursor: String?
        for _ in 0..<maxPages {
            let page = try await fetchRecentEvents(limit: 200, before: cursor)
            events.append(contentsOf: page.events)
            guard let oldest = page.events.last?.createdAt,
                  oldest >= since,
                  let next = page.nextCursor,
                  next != cursor,
                  !page.events.isEmpty
            else { break }
            cursor = next
        }
        return events.filter { $0.createdAt >= since }
    }

